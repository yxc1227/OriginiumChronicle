    /**
     * 挑不出人的种族：写下来并说明原因，页面据此不渲染图版。
     *
     * 温迪戈在本仓库只有爱国者一人，而他在来源侧没有立绘（PRTS 的立绘清单里没有他，
     * 见 `bin/fetch-splashes.py --prune-missing` 的清理记录）。这是**来源的边界**，
     * 不是采集的遗漏：不能因为「缺一张图」就去挑一个不属于这一族的人。
     */
    public const GAPS = [
        '温迪戈' => '本仓库该种族只有爱国者一人，来源侧没有他的立绘',
    ];

    /**
     * 执行接入：把裁定表写进 `races.illustration_id`。
     *
     * 与头像 / 立绘 / 徽记的 `associate()` 同一形状（返回统计而不是抛异常）：
     * 少一张图不该让整份 seed 失败，但少了什么必须逐条说出来。
     *
     * @return array{linked: int, gaps: list<string>, problems: list<string>}
     */
    public static function associate(): array
    {
        $races = Race::query()->orderBy('sort_order')->orderBy('id')->get();

        // 一次取回全部人物，按「种族 id|名字」建索引：36 条逐条 first() 就是几十次查询。
        // 只取有种族的行 —— 没有 race_id 的人不可能被裁定表点到（键里第一段就是种族）
        $characters = Character::query()->whereNotNull('race_id')->get()
            ->keyBy(fn (Character $character) => $character->race_id.'|'.$character->name);

        $linked = 0;
        $problems = [];
        $seen = [];

        foreach ($races as $race) {
            $name = self::SPECIMENS[$race->name] ?? null;

            if ($name === null) {
                // 裁定表与缺口表都没想到的种族：新增种族时在这里现形，不会安静地留空
                if (! isset(self::GAPS[$race->name])) {
                    $problems[] = $race->name.'：裁定表与缺口表里都没有它，本仓库尚未裁定用谁示意';
                }

                continue;
            }

            $seen[$race->name] = true;

            /** @var Character|null $character */
            $character = $characters->get($race->id.'|'.$name);

            if ($character === null) {
                // 分清两种失败：名字写错了，还是这个人根本不属于这一族
                $elsewhere = Character::query()->where('name', $name)->first();

                $problems[] = $elsewhere === null
                    ? $race->name.'：库里没有名为「'.$name.'」的人物'
                    : $race->name.'：「'.$name.'」的种族是'.($elsewhere->raceName() ?? '未登记')
                        .'，不是'.$race->name;

                continue;
            }

            // 立绘是这张图版的全部内容：没有立绘的人挂上去等于把卡片挖空一块
            if (! $character->hasSplash()) {
                $problems[] = $race->name.'：「'.$name.'」在来源侧没有立绘，示意不了';

                continue;
            }

            // 值没变就不写：seed 可以反复跑，不该每次都产生一堆无谓的 UPDATE
            if ((int) $race->illustration_id !== $character->id) {
                $race->fill(['illustration_id' => $character->id])->save();
            }

            $linked++;
        }

        // 裁定表里有、字典里没有的种族名：写错字就是在这里现形
        foreach (array_diff_key(self::SPECIMENS, $seen) as $name => $_) {
            $problems[] = '种族字典里没有「'.$name.'」这一条，无法裁定';
        }

        return [
            'linked' => $linked,
            'gaps' => array_keys(self::GAPS),
            'problems' => $problems,
        ];
    }
}
