 * 种族的示意立绘：本仓库裁定的「这一种族由哪位干员来示意」→ `races.illustration_id`。
 *
 * ## 为什么不用书里的插图
 *
 * 《大地巡旅》第四章「泰拉种族」确实是给每个种族配了整页图版的（一页一个种族，
 * 全身立绘加身高标尺），但那是印刷品里的图版，本项目手上没有可用的数字版；
 * 站外能找到的翻拍件是手机翻拍、分辨率与授权都够不上直接入库的门槛。
 * 因此这里改用**已经在库里的干员立绘**来示意 —— 图源与本仓库其他立绘同一批
 * （`docs/splashes.json` 记录的 PRTS 立绘），来源可追溯，页面上也已经标了出处。
 *
 * 页面上的措辞必须跟着这个事实走：那是**某位干员的立绘**，不是「这个种族的样子」。
 * 单个个体当然代表不了整个种族，所以卡片上写的是「示意」并点名是谁 ——
 * 让读者一眼看出这是一张替图，而不是把它当成书里那张图版。
 *
 * ## 人怎么挑的（这是本仓库的编辑裁定，不是书里的内容）
 *
 * 三条，按顺序：
 *
 *  1. **该种族里最容易被认出的那位**。辨识度优先于其他一切：这一张图的用处就是
 *     「让读者一眼想起这个种族长什么样」，认不出来就白挂了。
 *  2. **优先本体，不取异格 / 时装形态**。「假日威龙陈」是陈的夏日装扮、「焰影苇草」
 *     是苇草的异格 —— 拿一套特殊装扮当种族的门面，会让人以为那就是这个种族的样子。
 *     只有在同族**没有本体条目**时才退而用形态。
 *  3. **本仓库里有立绘**。没有立绘的名字挂上去只会渲染出一块空白
 *     （塔卫二的人员在来源侧全部没有立绘，历史人物不在干员名单里）。
 *
 * 挑选依据是名单本身的公开属性（星级、是否为异格形态）加上辨识度的判断，
 * 逐条写在下表里，改了哪一条在这里就能看到 —— 而不是散在某个脚本里算出来。
 * 要换人：改下面一行、跑一次 `db:seed`（或 `migrate:fresh --seed`）即可。
 *
 * ## 缺口是记下来的，不是漏掉的
 *
 * 确实挑不出人的种族写进 {@see GAPS} 并说明原因。表里没有的种族会被报成「未裁定」
 * —— 将来《大地巡旅》补录了新种族，它不会安静地留空，而是会在 seed 时被点名。
 */
